# --------------------------------------------------------------------------
# System (message type 4)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class System:
    protocol_version: int
    operator_location_type: int
    classification_type: int
    operator_latitude_deg: float | None
    operator_longitude_deg: float | None
    area_count: int
    area_radius_m: int
    area_ceiling_m: float | None
    area_floor_m: float | None
    category_eu: int
    class_eu: int
    operator_altitude_geo_m: float | None
    timestamp_s_since_2019: int
    message_type: int = MESSAGETYPE_SYSTEM


def _decode_system(data: bytes) -> System:
    byte0, byte1 = data[0], data[1]
    operator_location_type = byte1 & 0x03
    classification_type = (byte1 >> 2) & 0x07

    lat_enc, lon_enc = struct.unpack_from("<ii", data, 2)
    area_count, area_radius, area_ceiling_enc, area_floor_enc = struct.unpack_from(
        "<HBHH", data, 10
    )
    byte17 = data[17]
    class_eu = byte17 & 0x0F
    category_eu = byte17 >> 4
    operator_alt_enc, timestamp = struct.unpack_from("<HI", data, 18)

    operator_latitude_deg, operator_longitude_deg = _decode_latlon_pair(lat_enc, lon_enc)

    return System(
        protocol_version=byte0 & 0x0F,
        operator_location_type=operator_location_type,
        classification_type=classification_type,
        operator_latitude_deg=operator_latitude_deg,
        operator_longitude_deg=operator_longitude_deg,
        area_count=area_count,
        area_radius_m=area_radius * 10,
        area_ceiling_m=_decode_altitude(area_ceiling_enc),
        area_floor_m=_decode_altitude(area_floor_enc),
        category_eu=category_eu,
        class_eu=class_eu,
        operator_altitude_geo_m=_decode_altitude(operator_alt_enc),
        timestamp_s_since_2019=timestamp,
    )


