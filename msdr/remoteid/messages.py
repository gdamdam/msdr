"""ASTM F3411 / ASD-STAN Open Drone ID 25-byte message codec.

Derived from opendroneid-core-c (Apache-2.0,
https://github.com/opendroneid/opendroneid-core-c) at commit
6484f26545d4f012682524e2d843fab0fbdc0b34: libopendroneid/opendroneid.c and
opendroneid.h (field layout, unit conversions, sentinel "unknown"/"invalid"
encodings and the message-pack content limits). Hand-ported to Python and
cross-checked against tests/remoteid/data/vectors.json (independently
generated by linking the C sources -- see that directory's README), not
transliterated from the C.

Every function here is pure and never raises on attacker- or
corruption-controlled input: malformed or truncated buffers return a
`RemoteIdError`, matching the convention already used by
`msdr/wifi/dot11.py` (`Dot11Error`) and `msdr/ble/adv.py`.
"""

from __future__ import annotations

import struct
from dataclasses import dataclass, field

MESSAGE_SIZE = 25
ID_SIZE = 20
SELF_ID_DESC_SIZE = 23
AUTH_PAGE_ZERO_DATA_SIZE = 17
AUTH_PAGE_NONZERO_DATA_SIZE = 23
AUTH_MAX_PAGES = 16
PACK_MAX_MESSAGES = 9

MESSAGETYPE_BASIC_ID = 0
MESSAGETYPE_LOCATION = 1
MESSAGETYPE_AUTH = 2
MESSAGETYPE_SELF_ID = 3
MESSAGETYPE_SYSTEM = 4
MESSAGETYPE_OPERATOR_ID = 5
MESSAGETYPE_PACKED = 0xF

# Sentinel encodings (opendroneid.h MIN_*/MAX_*/INV_* macros): the decoded
# value that means "no value, invalid, or unknown". Never surfaced as a
# number -- always mapped to None.
_INV_DIR = 361.0
_INV_SPEED_H = 255.0
_INV_SPEED_V = 63.0
_INV_ALT = -1000.0
_INV_TIMESTAMP_ENC = 0xFFFF

_SPEED_DIV = (0.25, 0.75)
_VSPEED_DIV = 0.5
_LATLON_MULT = 10_000_000
_ALT_DIV = 0.5
_ALT_ADDER = 1000

# Accuracy enum -> decoded worst-case meters/seconds (opendroneid.c
# decode*Accuracy()). Enum value 0 is ODID_*_ACC_UNKNOWN in every one of
# these enums; its decoded value here is None, not the library's own
# worst-case default -- see this module's docstring.
_HORIZ_ACCURACY_M = {
    0: None,
    1: 18520.0,
    2: 7808.0,
    3: 3704.0,
    4: 1852.0,
    5: 926.0,
    6: 555.6,
    7: 185.2,
    8: 92.6,
    9: 30.0,
    10: 10.0,
    11: 3.0,
    12: 1.0,
}
_VERT_ACCURACY_M = {
    0: None,
    1: 150.0,
    2: 45.0,
    3: 25.0,
    4: 10.0,
    5: 3.0,
    6: 1.0,
}
_SPEED_ACCURACY_MS = {
    0: None,
    1: 10.0,
    2: 3.0,
    3: 1.0,
    4: 0.3,
}
_TIME_ACCURACY_S = {i: (None if i == 0 else i / 10) for i in range(16)}


def decode_horizontal_accuracy_m(enum_value: int) -> float | None:
    return _HORIZ_ACCURACY_M.get(enum_value)


def decode_vertical_accuracy_m(enum_value: int) -> float | None:
    return _VERT_ACCURACY_M.get(enum_value)


def decode_speed_accuracy_ms(enum_value: int) -> float | None:
    return _SPEED_ACCURACY_MS.get(enum_value)


def decode_timestamp_accuracy_s(enum_value: int) -> float | None:
    return _TIME_ACCURACY_S.get(enum_value)


@dataclass(frozen=True)
class RemoteIdError:
    kind: str  # "truncated" | "malformed" | "unsupported_type"
    detail: str


def _text_field(raw: bytes) -> str:
    """safe_dec_copyfill(): a C string -- stop at the first NUL, decode the
    rest as UTF-8 (falling back to a lossy decode on bad bytes rather than
    raising; these bytes are neighbour-controlled)."""
    end = raw.find(b"\x00")
    if end != -1:
        raw = raw[:end]
    return raw.decode("utf-8", errors="replace")


def _decode_direction(enc: int, ew: int) -> float | None:
    value = float(enc) + 180.0 if ew else float(enc)
    return None if value == _INV_DIR else value


def _decode_speed_horizontal(enc: int, mult: int) -> float | None:
    if mult:
        value = enc * _SPEED_DIV[1] + 255 * _SPEED_DIV[0]
    else:
        value = enc * _SPEED_DIV[0]
    return None if value == _INV_SPEED_H else value


def _decode_speed_vertical(enc: int) -> float | None:
    value = enc * _VSPEED_DIV
    return None if value == _INV_SPEED_V else value


def _decode_altitude(enc: int) -> float | None:
    value = enc * _ALT_DIV - _ALT_ADDER
    return None if value == _INV_ALT else value


def _decode_timestamp_s(enc: int) -> float | None:
    if enc == _INV_TIMESTAMP_ENC:
        return None
    return enc / 10


def _decode_latlon_pair(lat_enc: int, lon_enc: int) -> tuple[float | None, float | None]:
    if lat_enc == 0 and lon_enc == 0:
        return None, None
    return lat_enc / _LATLON_MULT, lon_enc / _LATLON_MULT


# --------------------------------------------------------------------------
# Basic ID (message type 0)
# --------------------------------------------------------------------------

#: ID types whose UASID bytes are a safe_dec_copyfill() C string (others --
#: UTM-assigned UUID, specific session id, or none -- are opaque binary).
_BASIC_ID_TEXT_TYPES = (1, 2)  # ODID_IDTYPE_SERIAL_NUMBER, ODID_IDTYPE_CAA_REGISTRATION_ID


@dataclass(frozen=True)
class BasicId:
    protocol_version: int
    ua_type: int
    id_type: int
    uas_id_bytes: bytes  # raw 20 bytes; the stable correlation/dedup key regardless of id_type
    uas_id_text: str | None  # decoded text, only for serial-number/CAA-registration id types
    message_type: int = MESSAGETYPE_BASIC_ID


def _decode_basic_id(data: bytes) -> BasicId | RemoteIdError:
    byte0, byte1 = data[0], data[1]
    id_type = byte1 >> 4
    ua_type = byte1 & 0x0F
    uas_id_bytes = data[2:22]
    uas_id_text = _text_field(uas_id_bytes) if id_type in _BASIC_ID_TEXT_TYPES else None
    return BasicId(
        protocol_version=byte0 & 0x0F,
        ua_type=ua_type,
        id_type=id_type,
        uas_id_bytes=uas_id_bytes,
        uas_id_text=uas_id_text,
    )


# --------------------------------------------------------------------------
# Location / Vector (message type 1)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Location:
    protocol_version: int
    status: int
    height_type: int
    direction_deg: float | None
    speed_horizontal_ms: float | None
    speed_vertical_ms: float | None
    latitude_deg: float | None
    longitude_deg: float | None
    altitude_baro_m: float | None
    altitude_geo_m: float | None
    height_m: float | None
    horiz_accuracy_enum: int
    vert_accuracy_enum: int
    baro_accuracy_enum: int
    speed_accuracy_enum: int
    timestamp_accuracy_enum: int
    timestamp_s: float | None  # tenths of a second since the top of the hour; wraps at 3600s
    message_type: int = MESSAGETYPE_LOCATION


def _decode_location(data: bytes) -> Location | RemoteIdError:
    byte0, byte1 = data[0], data[1]
    status = byte1 >> 4
    height_type = (byte1 >> 2) & 0x1
    ew_direction = (byte1 >> 1) & 0x1
    speed_mult = byte1 & 0x1

    (
        direction_enc,
        speed_h_enc,
        speed_v_enc,
        lat_enc,
        lon_enc,
        alt_baro_enc,
        alt_geo_enc,
        height_enc,
    ) = struct.unpack_from("<BBbiiHHH", data, 2)
    byte19 = data[19]
    horiz_accuracy_enum = byte19 & 0x0F
    vert_accuracy_enum = byte19 >> 4
    byte20 = data[20]
    speed_accuracy_enum = byte20 & 0x0F
    baro_accuracy_enum = byte20 >> 4
    (timestamp_enc,) = struct.unpack_from("<H", data, 21)
    timestamp_accuracy_enum = data[23] & 0x0F

    latitude_deg, longitude_deg = _decode_latlon_pair(lat_enc, lon_enc)

    return Location(
        protocol_version=byte0 & 0x0F,
        status=status,
        height_type=height_type,
        direction_deg=_decode_direction(direction_enc, ew_direction),
        speed_horizontal_ms=_decode_speed_horizontal(speed_h_enc, speed_mult),
        speed_vertical_ms=_decode_speed_vertical(speed_v_enc),
        latitude_deg=latitude_deg,
        longitude_deg=longitude_deg,
        altitude_baro_m=_decode_altitude(alt_baro_enc),
        altitude_geo_m=_decode_altitude(alt_geo_enc),
        height_m=_decode_altitude(height_enc),
        horiz_accuracy_enum=horiz_accuracy_enum,
        vert_accuracy_enum=vert_accuracy_enum,
        baro_accuracy_enum=baro_accuracy_enum,
        speed_accuracy_enum=speed_accuracy_enum,
        timestamp_accuracy_enum=timestamp_accuracy_enum,
        timestamp_s=_decode_timestamp_s(timestamp_enc),
    )


# --------------------------------------------------------------------------
# Authentication (message type 2)
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Authentication:
    protocol_version: int
    auth_type: int
    data_page: int
    last_page_index: int | None  # page 0 only
    length: int | None  # page 0 only; total authentication data bytes across all pages
    timestamp_s_since_2019: int | None  # page 0 only; relative to 2019-01-01T00:00:00Z
    auth_data: bytes
    message_type: int = MESSAGETYPE_AUTH


def _decode_auth(data: bytes) -> Authentication | RemoteIdError:
    byte0, byte1 = data[0], data[1]
    data_page = byte1 & 0x0F
    auth_type = byte1 >> 4
    if not (0 <= data_page <= AUTH_MAX_PAGES - 1):
        return RemoteIdError("malformed", f"auth data_page {data_page} out of range")

    if data_page == 0:
        last_page_index, length = data[2], data[3]
        (timestamp,) = struct.unpack_from("<I", data, 4)
        auth_data = data[8:25]
        if last_page_index >= AUTH_MAX_PAGES:
            return RemoteIdError(
                "malformed", f"auth last_page_index {last_page_index} out of range"
            )
        max_len = AUTH_PAGE_ZERO_DATA_SIZE + last_page_index * AUTH_PAGE_NONZERO_DATA_SIZE
        if length > max_len:
            return RemoteIdError(
                "malformed",
                f"auth length {length} exceeds {max_len} bytes for {last_page_index} pages",
            )
        return Authentication(
            protocol_version=byte0 & 0x0F,
            auth_type=auth_type,
            data_page=data_page,
            last_page_index=last_page_index,
            length=length,
            timestamp_s_since_2019=timestamp,
            auth_data=auth_data,
        )

    return Authentication(
        protocol_version=byte0 & 0x0F,
        auth_type=auth_type,
        data_page=data_page,
        last_page_index=None,
        length=None,
        timestamp_s_since_2019=None,
        auth_data=data[2:25],
    )


