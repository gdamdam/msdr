DecodedMessage = BasicId | Location | Authentication | SelfId | System | OperatorId

_DECODERS = {
    MESSAGETYPE_BASIC_ID: _decode_basic_id,
    MESSAGETYPE_LOCATION: _decode_location,
    MESSAGETYPE_AUTH: _decode_auth,
    MESSAGETYPE_SELF_ID: _decode_self_id,
    MESSAGETYPE_SYSTEM: _decode_system,
    MESSAGETYPE_OPERATOR_ID: _decode_operator_id,
}


def decode_message(data: bytes) -> DecodedMessage | RemoteIdError:
    """Decode one 25-byte Open Drone ID message. Returns `RemoteIdError` for
    anything truncated, oversized-but-still-one-message, an unsupported
    message type, or a type-specific validity failure; never raises."""
    if len(data) != MESSAGE_SIZE:
        return RemoteIdError("truncated", f"message is {len(data)} bytes, expected {MESSAGE_SIZE}")
    message_type = data[0] >> 4
    decoder = _DECODERS.get(message_type)
    if decoder is None:
        return RemoteIdError("unsupported_type", f"message type {message_type}")
    return decoder(data)


# --------------------------------------------------------------------------
# Message Pack (message type 0xF)
# --------------------------------------------------------------------------

# checkPackContent(): at most this many of each type per pack.
_PACK_TYPE_LIMITS = {
    MESSAGETYPE_BASIC_ID: 2,
    MESSAGETYPE_LOCATION: 1,
    MESSAGETYPE_AUTH: AUTH_MAX_PAGES,
    MESSAGETYPE_SELF_ID: 1,
    MESSAGETYPE_SYSTEM: 1,
    MESSAGETYPE_OPERATOR_ID: 1,
}


@dataclass(frozen=True)
class MessagePack:
    protocol_version: int
    message_count: int
    messages: tuple[DecodedMessage, ...] = field(default_factory=tuple)
    errors: tuple[RemoteIdError, ...] = field(default_factory=tuple)


def decode_message_pack(data: bytes) -> MessagePack | RemoteIdError:
    """Decode a `[type/version][single_size][count][messages...]` Message
    Pack buffer (opendroneid's `ODID_MessagePack_encoded`). Individual
    message decode failures are collected in `.errors`, not hidden; the pack
    itself only fails for a structurally-malformed header or illegal
    message-type content (`checkPackContent()`)."""
    if len(data) < 3:
        return RemoteIdError("truncated", "message pack header")
    message_type = data[0] >> 4
    if message_type != MESSAGETYPE_PACKED:
        return RemoteIdError("malformed", f"not a message pack (type {message_type})")
    single_size, count = data[1], data[2]
    if single_size != MESSAGE_SIZE:
        return RemoteIdError("malformed", f"single message size {single_size} != {MESSAGE_SIZE}")
    if not (1 <= count <= PACK_MAX_MESSAGES):
        return RemoteIdError("malformed", f"message pack count {count} out of range")
    needed = 3 + count * MESSAGE_SIZE
    if len(data) < needed:
        return RemoteIdError("truncated", f"message pack needs {needed} bytes, has {len(data)}")

    raw_messages = [data[3 + i * MESSAGE_SIZE : 3 + (i + 1) * MESSAGE_SIZE] for i in range(count)]
    type_counts: dict[int, int] = {}
    for raw in raw_messages:
        mtype = raw[0] >> 4
        if mtype not in _PACK_TYPE_LIMITS:
            return RemoteIdError("malformed", f"illegal message type {mtype} inside pack")
        type_counts[mtype] = type_counts.get(mtype, 0) + 1
    for mtype, limit in _PACK_TYPE_LIMITS.items():
        if type_counts.get(mtype, 0) > limit:
            return RemoteIdError("malformed", f"too many type {mtype} messages in pack")

    messages: list[DecodedMessage] = []
    errors: list[RemoteIdError] = []
    for raw in raw_messages:
        decoded = decode_message(raw)
        if isinstance(decoded, RemoteIdError):
            errors.append(decoded)
        else:
            messages.append(decoded)

    return MessagePack(
        protocol_version=data[0] & 0x0F,
        message_count=count,
        messages=tuple(messages),
        errors=tuple(errors),
    )
