"""RttyDecoder on synthesized 2-tone FSK (ITA2) and, when `minimodem` is on
PATH, a reference WAV generated by `minimodem --tx` at test time.

SYNTHETIC: validates the port's estimators (mark/space/shift/baud/polarity)
and the Baudot framing round-trip, not off-air reception -- see
capability_matrix MATRIX["rtty"].
"""

import shutil
import subprocess
import wave

import numpy as np
import pytest

from msdr.decoder.pydecoders.rtty import _ITA2_FIGURES, _ITA2_LETTERS, PRESETS, RttyDecoder

_FS = 11_025
_LTRS_CODE = _ITA2_LETTERS.index(">")
_FIGS_CODE = _ITA2_LETTERS.index("<")
_LETTER_TO_CODE = {ch: i for i, ch in enumerate(_ITA2_LETTERS) if ch not in ("\x00", "<", ">")}
_FIGURE_TO_CODE = {ch: i for i, ch in enumerate(_ITA2_FIGURES) if ch not in ("\x00", "<", ">")}
_RANDOM_LETTERS = [ch for ch in _LETTER_TO_CODE if ch != " "]


def _encode(text: str) -> list[int]:
    codes = []
    state = "letters"
    for ch in text:
        if ch == " ":
            codes.append(_LETTER_TO_CODE[" "])
        elif ch in _LETTER_TO_CODE:
            if state != "letters":
                codes.append(_LTRS_CODE)
                state = "letters"
            codes.append(_LETTER_TO_CODE[ch])
        elif ch in _FIGURE_TO_CODE:
            if state != "figures":
                codes.append(_FIGS_CODE)
                state = "figures"
            codes.append(_FIGURE_TO_CODE[ch])
        else:
            raise ValueError(f"unsupported test character: {ch!r}")
    return codes


def _random_preamble(n: int, seed: int = 0) -> str:
    # Non-periodic (unlike the classic "RY" tuning diddle): a repeating
    # "RY" preamble gives the fastest baud-histogram convergence, but its
    # periodic spectrum biases the FFT tone-pair estimate inward by tens of
    # Hz (comb lines spaced by the baud rate around each real tone). Random
    # letters still toggle enough bits for the edge histogram without that
    # bias.
    rng = np.random.default_rng(seed)
    return "".join(rng.choice(_RANDOM_LETTERS) for _ in range(n))


def synth_rtty(
    text: str,
    baud: float,
    shift_hz: float,
    *,
    fs: int = _FS,
    center_hz: float = 1500.0,
    inverted: bool = False,
    snr_db: float | None = None,
    seed: int = 0,
) -> np.ndarray:
    """Continuous-phase 2-tone FSK, 1 start + 5 ITA2 data (LSB-first) + 1
    stop bit per character, optionally with AWGN at the given SNR (ratio of
    single-tone power to noise power)."""
    codes = _encode(text)
    mark_hz, space_hz = center_hz + shift_hz / 2, center_hz - shift_hz / 2
    if inverted:
        mark_hz, space_hz = space_hz, mark_hz
    bits: list[int] = []
    for code in codes:
        bits.append(0)  # start bit (space)
        bits.extend((code >> i) & 1 for i in range(5))  # LSB first
        bits.append(1)  # stop bit (mark)
    samples_per_bit = fs / baud
    phase = 0.0
    chunks = []
    acc = 0.0
    for bit in bits:
        acc += samples_per_bit
        n = int(round(acc))
        acc -= n
        freq = mark_hz if bit else space_hz
        t = np.arange(n)
        chunks.append(np.cos(2 * np.pi * freq * t / fs + phase))
        phase = (phase + 2 * np.pi * freq * n / fs) % (2 * np.pi)
    audio = np.concatenate(chunks).astype(np.float64)
    if snr_db is not None:
        rng = np.random.default_rng(seed)
        noise_power = 0.5 / (10 ** (snr_db / 10))
        audio = audio + rng.normal(0.0, np.sqrt(noise_power), size=audio.shape)
    return audio.astype(np.float32)


def _decode(audio: np.ndarray, **kwargs) -> tuple[str, RttyDecoder]:
    dec = RttyDecoder(**kwargs)
    events = dec.feed(audio)
    events += dec.flush()
    return "".join(e.text for e in events), dec


_MSG = "THE QUICK BROWN FOX 123"


@pytest.mark.parametrize(
    "baud,shift_hz,inverted",
    [
        (45.45, 170.0, False),  # amateur
        (50.0, 450.0, False),  # NWS/marine (wide shift)
        (75.0, 850.0, False),  # faster baud, very wide shift
        (45.45, 170.0, True),  # reversed (inverted) mark/space
    ],
)
def test_auto_detects_rate_shift_and_polarity(baud, shift_hz, inverted):
    text_in = _random_preamble(260) + " " + _MSG + "\r\n"
    audio = synth_rtty(text_in, baud, shift_hz, inverted=inverted)
    text, dec = _decode(audio)
    assert _MSG in text
    assert dec.estimate_source == "auto"
    assert dec.inverted == inverted
    assert abs(dec.baud - baud) <= 5.0
    assert abs(dec.shift_hz - shift_hz) <= 20.0


def test_noise_only_has_no_characters():
    rng = np.random.default_rng(1)
    noise = rng.normal(0.0, 0.3, size=_FS * 15).astype(np.float32)
    text, _dec = _decode(noise)
    assert text == ""


def test_exact_text_above_stated_snr():
    msg = "HELLO WORLD THIS IS A TEST MESSAGE"
    audio = synth_rtty(_random_preamble(260) + " " + msg + "\r\n", 45.45, 170.0, snr_db=15.0)
    text, _dec = _decode(audio)
    assert msg in text


def test_preset_mode_locks_without_estimating_baud():
    audio = synth_rtty(_random_preamble(60) + " " + _MSG + "\r\n", 45.45, 170.0)
    text, dec = _decode(audio, mode="amateur_45_170")
    assert _MSG in text
    assert dec.estimate_source == "preset"
    assert dec.baud == PRESETS["amateur_45_170"][0]
    assert dec.shift_hz == PRESETS["amateur_45_170"][1]


def test_weather_marine_presets_defined():
    assert PRESETS["weather_50_450"] == (50.0, 450.0)
    assert PRESETS["weather_50_85"] == (50.0, 85.0)


@pytest.mark.skipif(shutil.which("minimodem") is None, reason="minimodem not installed")
def test_decodes_minimodem_reference_wav(tmp_path):
    """Independent reference: minimodem (GPL) is used only to generate a
    fixture at test time, never bundled."""
    msg = "HELLO WORLD FROM MINIMODEM"
    wav_path = tmp_path / "rtty_ref.wav"
    tx_text = ("RY" * 30) + " " + msg + "\r\n"
    subprocess.run(
        [
            "minimodem",
            "--tx",
            "-5",
            "-M",
            "2295",
            "-S",
            "2125",
            "-R",
            str(_FS),
            "--stopbits",
            "1",
            "45.45",
            "-f",
            str(wav_path),
            "-q",
        ],
        input=tx_text,
        text=True,
        check=True,
        capture_output=True,
    )
    with wave.open(str(wav_path), "rb") as w:
        pcm = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2")
        audio = pcm.astype(np.float32) / 32768.0
    text, dec = _decode(audio)
    assert msg in text
    assert abs(dec.baud - 45.45) <= 5.0
    assert abs(dec.shift_hz - 170.0) <= 20.0
